/**
 * Acceptance matrix against the REAL, unmodified kit mock over HTTP.
 * Every test resets the mock, so results and counters are reproducible.
 */
import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { FIXTURES, fixture, makeController, memoryStorage, nodeFileStore, picked, reset, scenario, startKitMock, stats, waitFor } from './support/node-deps';
import { setLogSink } from '../src/log/logger';

let baseUrl: string;
let stop: () => Promise<void>;
const logLines: string[] = [];

beforeAll(async () => {
  // oversize.csv is generated by the kit's own command (not committed).
  if (!fs.existsSync(fixture('oversize.csv'))) {
    execFileSync(process.execPath, [path.join(FIXTURES, '..', 'make-oversize.mjs')]);
  }
  ({ baseUrl, stop } = await startKitMock());
  setLogSink(l => logLines.push(l));
});
afterAll(() => stop());
beforeEach(async () => {
  await reset(baseUrl);
  logLines.length = 0;
});

async function importFile(name: string, c = makeController(baseUrl)) {
  await c.controller.prepare(picked(name));
  expect(c.controller.snapshot.draft).not.toBeNull();
  await c.controller.confirm();
  return c;
}

test('happy: real bytes sent, 202 is not a report, ready shows the mock data (csv + pdf)', async () => {
  for (const name of ['statement.csv', 'statement.pdf']) {
    await reset(baseUrl);
    const { controller } = await importFile(name);
    const after202 = controller.snapshot.op!;
    expect(after202.send).toBe('acked');
    expect(after202.job!.status).not.toBe('ready');
    expect(after202.job!.result).toBeUndefined();
    await waitFor(() => controller.snapshot.op!.job!.status === 'ready');
    const result = controller.snapshot.op!.job!.result!;
    expect(result.currency).toBe('AUD');
    expect(result.items.map(i => i.merchant)).toEqual(['StreamBeam', 'BrightGrid']);
    expect(result.items.reduce((s, i) => s + i.amountMinor, 0)).toBe(15199);
    const s = await stats(baseUrl);
    expect(s.newJobs).toBe(1);
    expect(s.acceptedBytes).toBe(fs.statSync(fixture(name)).size);
    controller.dispose();
  }
});

test('persisted key: key is durably stored before the POST; relaunch reuses it and does not POST again', async () => {
  const storage = memoryStorage();
  const files = nodeFileStore();
  const first = makeController(baseUrl, { storage, files });
  let writesAtPost = -1;
  const before = (await stats(baseUrl)).createRequests;
  // Observe the moment the create request is issued.
  const origCreate = first.api.createImport;
  first.api.createImport = async (...args) => {
    writesAtPost = storage.writes.length;
    return origCreate(...args);
  };
  await first.controller.prepare(picked('statement.csv'));
  await first.controller.confirm();
  const key = first.controller.snapshot.op!.importKey;
  // At POST time the key had already been written (pending + sending).
  expect(writesAtPost).toBeGreaterThanOrEqual(1);
  expect(storage.writes[0]!.importKey).toBe(key);
  expect(storage.writes[0]!.send).toBe('pending');
  first.controller.dispose();

  // Relaunch from the same storage.
  const second = makeController(baseUrl, { storage, files });
  await second.controller.start();
  expect(second.controller.snapshot.op!.importKey).toBe(key);
  expect((await stats(baseUrl)).createRequests).toBe(before + 1);
  second.controller.dispose();
});

test('lost_ack: first POST commits without a response; recovery by key finds it; exactly one job (incl. relaunch + retry)', async () => {
  await scenario(baseUrl, 'lost_ack');
  const storage = memoryStorage();
  const files = nodeFileStore();
  const first = makeController(baseUrl, { storage, files });
  await first.controller.prepare(picked('statement.csv'));
  await first.controller.confirm();
  // Lost response -> unknown -> GET by-key recovered the job without a resend.
  const op = first.controller.snapshot.op!;
  expect(op.send).toBe('acked');
  expect(op.job!.jobId).toBe('job-demo-001');
  expect(files.list()).toEqual([]); // private copy removed once the job is confirmed
  first.controller.dispose();

  // Simulate a crash during the POST: persisted state says "sending"; relaunch must not resend.
  const crashed = { ...op, send: 'sending' as const, job: undefined };
  const relaunch = makeController(baseUrl, { storage: memoryStorage(crashed), files });
  const createsBefore = (await stats(baseUrl)).createRequests;
  await relaunch.controller.start();
  expect(relaunch.controller.snapshot.op!.job!.jobId).toBe('job-demo-001');
  expect((await stats(baseUrl)).createRequests).toBe(createsBefore);
  relaunch.controller.dispose();
  expect((await stats(baseUrl)).newJobs).toBe(1);
});

test('lost_ack: retry with the SAME key after by-key 404 does not create a second job', async () => {
  await scenario(baseUrl, 'lost_ack');
  const c = makeController(baseUrl);
  // Make the first by-key lookup miss (as if the original request was still in flight).
  const realGetByKey = c.api.getByKey;
  let misses = 1;
  c.api.getByKey = async k => (misses-- > 0 ? { kind: 'http', status: 404 } : realGetByKey(k));
  await c.controller.prepare(picked('statement.csv'));
  await c.controller.confirm();
  expect(c.controller.snapshot.op!.send).toBe('unknown');
  expect(c.controller.snapshot.op!.sendError).toBe('not_found');
  await scenario(baseUrl, 'happy');
  await c.controller.retrySend();
  expect(c.controller.snapshot.op!.job!.jobId).toBe('job-demo-001');
  const s = await stats(baseUrl);
  expect(s.newJobs).toBe(1);
  expect(s.duplicateHits).toBe(1);
  c.controller.dispose();
});

test('stale_status: ready/rev3 then processing/rev2 does not roll the state back', async () => {
  const { controller } = await importFile('statement.csv');
  await waitFor(() => controller.snapshot.op!.job!.status === 'ready');
  await scenario(baseUrl, 'stale_status');
  const seen: string[] = [];
  controller.subscribe(s => seen.push(`${s.op?.job?.status}/${s.op?.job?.revision}`));
  await controller.manualRefresh(); // server: ready r3
  await controller.manualRefresh(); // server: processing r2 (stale)
  await controller.manualRefresh(); // server: ready r3
  expect(controller.snapshot.op!.job).toMatchObject({ status: 'ready', revision: 3 });
  expect(controller.snapshot.op!.job!.result!.items).toHaveLength(2);
  expect(seen.some(s => s.startsWith('processing'))).toBe(false);
  controller.dispose();
});

test('delete_failure: 503 is not deletion; after happy, retry with the same key reaches deleted', async () => {
  const { controller } = await importFile('statement.csv');
  await waitFor(() => controller.snapshot.op!.job!.status === 'ready');
  await scenario(baseUrl, 'delete_failure');
  await controller.requestDelete();
  let op = controller.snapshot.op!;
  expect(op.del).toMatchObject({ state: 'failed', error: 'server_error' });
  expect(op.job!.status).toBe('ready');
  const firstKey = op.del!.key;

  await scenario(baseUrl, 'happy');
  await controller.requestDelete();
  op = controller.snapshot.op!;
  expect(op.del).toMatchObject({ key: firstKey, state: 'accepted' });
  expect(op.job!.status).toBe('deleting'); // accepted, but NOT deleted yet
  await waitFor(() => controller.snapshot.op!.job!.status === 'deleted', 4000);
  expect(controller.snapshot.op!.job!.result).toBeUndefined();
  expect((await stats(baseUrl)).deleteRequests).toBe(2);
  controller.dispose();
});

test('late response does not resurrect a deleted job', async () => {
  const { controller, api } = await importFile('statement.csv');
  await waitFor(() => controller.snapshot.op!.job!.status === 'ready');
  // A status GET is in flight while the job is ready; its response is delivered only after deletion completed.
  const realGetJob = api.getJob;
  let release!: () => void;
  const gate = new Promise<void>(r => (release = r));
  api.getJob = async id => {
    const view = await realGetJob(id); // ready / r3
    await gate;
    return view;
  };
  const late = controller.refresh();
  await new Promise(r => setTimeout(r, 50));
  api.getJob = realGetJob;
  await controller.requestDelete();
  await waitFor(() => controller.snapshot.op!.job!.status === 'deleted', 4000);
  release();
  await late;
  await controller.idle();
  expect(controller.snapshot.op!.job).toMatchObject({ status: 'deleted', revision: 5 });
  expect(controller.snapshot.op!.job!.result).toBeUndefined();
  // Even a bogus higher revision after deletion is ignored (terminal state).
  api.getJob = async () => ({ kind: 'ok', status: 200, data: { jobId: 'job-demo-001', status: 'ready', revision: 9 } });
  await controller.refresh();
  expect(controller.snapshot.op!.job!.status).toBe('deleted');
  controller.dispose();
});

test('spoofed.pdf and oversize.csv are rejected locally before any POST (createRequests unchanged)', async () => {
  const before = (await stats(baseUrl)).createRequests;
  const c = makeController(baseUrl);
  await c.controller.prepare(picked('spoofed.pdf'));
  expect(c.controller.snapshot.rejection).toBe('unrecognized_content');
  expect(c.controller.snapshot.draft).toBeNull();
  await c.controller.prepare(picked('oversize.csv'));
  expect(c.controller.snapshot.rejection).toBe('too_large');
  expect(c.controller.snapshot.draft).toBeNull();
  expect(c.files.list()).toEqual([]); // nothing staged
  expect((await stats(baseUrl)).createRequests).toBe(before);
  c.controller.dispose();
});

test('logs never contain the file name, bytes or descriptions', async () => {
  const { controller } = await importFile('statement.csv');
  await waitFor(() => controller.snapshot.op!.job!.status === 'ready');
  await controller.requestDelete();
  await waitFor(() => controller.snapshot.op!.job!.status === 'deleted', 4000);
  const all = logLines.join('\n');
  expect(logLines.length).toBeGreaterThan(0);
  for (const forbidden of ['statement', 'StreamBeam', 'BrightGrid', 'description', '.csv', 'file:', FIXTURES]) {
    expect(all).not.toContain(forbidden);
  }
  controller.dispose();
});
